#!/usr/bin/env python3
"""Compare two classification systems citation by citation and write a markdown error analysis.

Aggregate F1 says *whether* a system is better; this says *where*. Each test citation is joined
to its fine-grained annotation label (the nine labels before the 3-way collapse) and to how much
of its gold evidence each system's retrieval kept, then the two systems are compared:

  1. confusion matrices, gold -> predicted;
  2. accuracy per fine-grained label, with the citations each system alone gets right;
  3. accuracy by evidence coverage (none annotated / all, some or none retrieved), each system
     bucketed by its own retrieval, since that is the evidence it actually read;
  4. accuracy per reference article, since test is 20 articles and a gain carried by one or two
     of them would not generalise;
  5. examples of citations fixed and of the most confident remaining errors.

    python scripts/error_analysis.py \\
        --base results/classification/test/paper_20.jsonl --base-export data_train/target/paper_20_test \\
        --system results/classification/ensemble/test.jsonl --system-export data_train/target/ours_20_test \\
        --out results/error_analysis.md
"""
import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

LABELS = ['ACCURATE', 'NOT_ACCURATE', 'NOT ENOUGH INFO']
ROOT = Path(__file__).resolve().parents[1]
FINE_ORDER = ['ACCURATE', 'INDIRECT', 'INDIRECT_NOT_REVIEW', 'CONTRADICT', 'NOT_SUBSTANTIATE',
              'OVERSIMPLIFY', 'MISQUOTE', 'ETIQUETTE', 'IRRELEVANT']


def read_jsonl(path):
    with open(path, encoding='utf8') as f:
        return [json.loads(x) for x in f if x.strip()]


def coverage(export, split, n_gold):
    """Per citation: 'no gold' or the share of its gold sentences the export's document kept."""
    out = {}
    for c in read_jsonl(Path(export) / f'claims_{split}.jsonl'):
        kept = sum(len(e['sentences']) for items in c.get('evidence', {}).values() for e in items)
        g = n_gold[c['id']]
        out[c['id']] = ('none annotated' if g == 0 else 'all retrieved' if kept >= g
                        else 'none retrieved' if kept == 0 else 'some retrieved')
    return out


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in rows]
    return '\n'.join(lines)


def pct(n, d):
    return f'{n / d:.3f}' if d else '—'


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--base', type=Path, required=True)
    p.add_argument('--base-export', type=Path, required=True)
    p.add_argument('--base-name', default='paper system')
    p.add_argument('--system', type=Path, required=True)
    p.add_argument('--system-export', type=Path, required=True)
    p.add_argument('--system-name', default='ensemble')
    p.add_argument('--split', default='test')
    p.add_argument('--data-dir', type=Path,
                   default=ROOT / 'upstream/Citation-Integrity/Data/multivers-format')
    p.add_argument('--annotations', type=Path)
    p.add_argument('--examples', type=int, default=4)
    p.add_argument('--out', type=Path, required=True)
    a = p.parse_args()

    base = {r['id']: r for r in read_jsonl(a.base)}
    sysp = {r['id']: r for r in read_jsonl(a.system)}
    if set(base) != set(sysp):
        raise SystemExit('the two prediction files cover different citations')
    ids = sorted(base)
    gold = {i: base[i]['gold'] for i in ids}
    if any(sysp[i]['gold'] != gold[i] for i in ids):
        raise SystemExit('the two prediction files disagree on gold labels')

    ann = {r['id']: r for r in read_jsonl(a.annotations or ROOT / f'results/annotations/{a.split}.jsonl')}
    claims = {c['id']: c for c in read_jsonl(a.data_dir / f'claims-{a.split}.jsonl')}
    n_gold = {i: sum(len(e['sentences']) for items in claims[i].get('evidence', {}).values()
                     for e in items) for i in ids}
    cov = {'base': coverage(a.base_export, a.split, n_gold),
           'system': coverage(a.system_export, a.split, n_gold)}
    B, S = a.base_name, a.system_name
    ok_b = {i: base[i]['prediction'] == gold[i] for i in ids}
    ok_s = {i: sysp[i]['prediction'] == gold[i] for i in ids}

    out = [f'# Error analysis: {S} against {B}, {a.split} split ({len(ids)} citations)', '',
           f'Generated by `scripts/error_analysis.py`. {B}: `{a.base}` on `{a.base_export}`. '
           f'{S}: `{a.system}` on `{a.system_export}`.', '']
    only_s, only_b = sum(ok_s[i] and not ok_b[i] for i in ids), sum(ok_b[i] and not ok_s[i] for i in ids)
    out += [f'Accuracy {pct(sum(ok_b.values()), len(ids))} for {B} and '
            f'{pct(sum(ok_s.values()), len(ids))} for {S}. {S} alone is right on {only_s} '
            f'citations and {B} alone on {only_b}; both are wrong on '
            f'{sum(not ok_b[i] and not ok_s[i] for i in ids)}.', '']

    out += ['## 1. Confusion matrices (rows gold, columns predicted)', '']
    for name, pr in ((B, base), (S, sysp)):
        cm = Counter((gold[i], pr[i]['prediction']) for i in ids)
        out += [f'**{name}**', '', table(['gold \\ predicted'] + LABELS,
                [[g] + [cm[g, q] for q in LABELS] for g in LABELS]), '']

    out += ['## 2. By fine-grained label', '',
            'The 3-way label each fine label collapses to is in brackets. "Fixed" is right only '
            f'under {S}; "broken" is right only under {B}.', '']
    rows = []
    for f in FINE_ORDER:
        fi = [i for i in ids if ann[i]['label'] == f]
        if not fi:
            continue
        rows.append([f'{f} [{gold[fi[0]]}]', len(fi), pct(sum(ok_b[i] for i in fi), len(fi)),
                     pct(sum(ok_s[i] for i in fi), len(fi)),
                     sum(ok_s[i] and not ok_b[i] for i in fi), sum(ok_b[i] and not ok_s[i] for i in fi)])
    out += [table(['fine label', 'n', f'{B} acc', f'{S} acc', 'fixed', 'broken'], rows), '']

    out += ['## 3. By evidence coverage', '',
            'Each system is bucketed by its own retrieval, the evidence it actually read. "None '
            'annotated" citations have no gold evidence sentences (mostly ETIQUETTE and IRRELEVANT).', '']
    rows = []
    for bucket in ('all retrieved', 'some retrieved', 'none retrieved', 'none annotated'):
        bb = [i for i in ids if cov['base'][i] == bucket]
        sb = [i for i in ids if cov['system'][i] == bucket]
        rows.append([bucket, len(bb), pct(sum(ok_b[i] for i in bb), len(bb)),
                     len(sb), pct(sum(ok_s[i] for i in sb), len(sb))])
    out += [table(['gold evidence', f'{B} n', f'{B} acc', f'{S} n', f'{S} acc'], rows), '']

    out += ['## 4. By reference article', '']
    by_art = defaultdict(list)
    for i in ids:
        by_art[ann[i]['reference']].append(i)
    rows, wins, losses = [], 0, 0
    for art in sorted(by_art):
        ai = by_art[art]
        d = sum(ok_s[i] for i in ai) - sum(ok_b[i] for i in ai)
        wins += d > 0
        losses += d < 0
        rows.append([art, len(ai), pct(sum(ok_b[i] for i in ai), len(ai)),
                     pct(sum(ok_s[i] for i in ai), len(ai)), f'{d:+d}'])
    out += [f'{S} is more accurate on {wins} of {len(by_art)} articles and less accurate on '
            f'{losses}.', '', table(['article', 'n', f'{B} acc', f'{S} acc', 'net citations'], rows), '']

    def example(i):
        claim = claims[i]['claim']
        claim = claim if len(claim) <= 220 else claim[:217] + '...'
        claim = claim.replace('|', '\\|')  # citation markers like <|cit|> would split the table
        return [i, ann[i]['label'], base[i]['prediction'], sysp[i]['prediction'],
                f'{max(sysp[i]["probs"].values()):.2f}', claim]

    out += ['## 5. Examples', '', f'**Fixed**: right under {S}, wrong under {B}.', '']
    fixed = [i for i in ids if ok_s[i] and not ok_b[i]]
    picks = []
    for f in FINE_ORDER:  # spread the examples over fine labels rather than taking the first few
        picks += [i for i in fixed if ann[i]['label'] == f][:1]
    out += [table(['id', 'fine label', B, S, f'{S} conf.', 'citing sentence'],
                  [example(i) for i in picks[:a.examples]]), '']
    wrong = sorted((i for i in ids if not ok_s[i]), key=lambda i: -max(sysp[i]['probs'].values()))
    out += [f'**Most confident remaining errors** of {S}.', '',
            table(['id', 'fine label', B, S, f'{S} conf.', 'citing sentence'],
                  [example(i) for i in wrong[:a.examples]]), '']

    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text('\n'.join(out), encoding='utf8')
    print(f'wrote {a.out}')


if __name__ == '__main__':
    main()
